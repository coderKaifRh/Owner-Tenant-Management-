package com.tak.web.model;

import jakarta.persistence.*;

@Entity
@Table(name = "users")
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "user_id")
    private Integer userId;

    @Column(name = "username", nullable = false, unique = true)
    private String username;

    @Column(name = "password", nullable = false)
    private String password;

    @Column(name = "role", nullable = false)
    private String role; // "Owner" or "Tenant"

    public User() {}

    public User(String username, String password, String role) {
        this.username = username;
        this.password = password;
        this.role = role;
    }

    public Integer getUserId() { return userId; }
    public void setUserId(Integer userId) { this.userId = userId; }

    public String getUsername() { return username; }
    public void setUsername(String username) { this.username = username; }

    public String getPassword() { return password; }
    public void setPassword(String password) { this.password = password; }

    public String getRole() { return role; }
    public void setRole(String role) { this.role = role; }

    public boolean isOwner() { return "Owner".equalsIgnoreCase(role); }
    public boolean isTenant() { return "Tenant".equalsIgnoreCase(role); }

    public double calculateAdvance(double rent) {
        if (isOwner()) {
            return rent * 0.05; // 5% listing fee for owner
        } else {
            return rent * 2; // 2 months advance for tenant
        }
    }
}
